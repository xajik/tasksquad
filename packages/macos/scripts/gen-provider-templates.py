#!/usr/bin/env python3
"""Regenerates Sources/TaskSquadCore/ProviderTemplates.swift from the Go
provider templates (packages/daemon/provider/{opencode,pi}.go) so the files
both daemons write into work directories stay byte-identical.

Run from packages/macos: python3 scripts/gen-provider-templates.py
ProviderGoldenTests fails when the Go templates change and this was not rerun."""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GO = os.path.join(ROOT, "..", "daemon", "provider")


def backticks(name):
    return re.findall(r"`([^`]*)`", open(os.path.join(GO, name)).read(), re.S)


def alternate(text):
    """Go passes agentID, taskID pairs to consecutive %s verbs."""
    count = 0

    def token(_):
        nonlocal count
        count += 1
        return "{{AGENT}}" if count % 2 else "{{TASK}}"

    return re.sub(r"%s", token, text)


opencode = backticks("opencode.go")
analytics = next(b for b in opencode if b.startswith("const lifecycleURL"))
plugin = next(b for b in opencode if b.startswith("// Auto-generated"))
pi = next(b for b in backticks("pi.go") if b.startswith("// Auto-generated"))
assert "%%" not in plugin + analytics + pi
plugin = alternate(plugin.replace("%d", "{{PORT}}", 1))
analytics = alternate(analytics)
pi = pi.replace("%[1]d", "{{PORT}}").replace("%[2]s", "{{AGENT}}").replace("%[3]s", "{{TASK}}")


def literal(name, text):
    assert '"""#' not in text
    # The line break before the closing delimiter is not part of the value.
    return f'    static let {name} = #"""\n{text}\n"""#\n'


source = (
    "// Generated by scripts/gen-provider-templates.py from packages/daemon/provider/{opencode,pi}.go.\n"
    "// Do not edit: keep byte-identical with Go. {{PORT}}, {{AGENT}} and {{TASK}} replace Go's fmt verbs.\n\n"
    "enum ProviderTemplates {\n"
    + literal("openCodePlugin", plugin)
    + literal("openCodeAnalytics", analytics)
    + literal("piExtension", pi)
    + """
    static func render(_ template: String, port: Int, agentID: String, taskID: String) -> String {
        template.replacingOccurrences(of: "{{PORT}}", with: String(port))
            .replacingOccurrences(of: "{{AGENT}}", with: agentID).replacingOccurrences(of: "{{TASK}}", with: taskID)
    }
}
"""
)
open(os.path.join(ROOT, "Sources", "TaskSquadCore", "ProviderTemplates.swift"), "w").write(source)
