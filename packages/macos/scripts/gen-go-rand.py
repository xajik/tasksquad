#!/usr/bin/env python3
"""Generates ../tsq-core/Sources/TaskSquadCore/GoRand.swift: Go's math/rand (Go 1 source)
seed table, so Swift derives the same seeded sequence as the Go daemon (the
Dreamer's nightly trigger time). Run: python3 scripts/gen-go-rand.py "$(go env GOROOT)"."""
import os, re, sys

source = open(os.path.join(sys.argv[1], "src", "math", "rand", "rng.go")).read()
body = source[source.index("rngCooked [rngLen]int64 = [...]int64{"):]
body = body[body.index("{") + 1:body.index("}")]
values = re.findall(r"-?\d+", body)
assert len(values) == 607, len(values)
rows = [", ".join(values[i:i + 4]) for i in range(0, len(values), 4)]
out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "..", "tsq-core", "Sources", "TaskSquadCore", "GoRand.swift")
open(out, "w").write(
    "// Generated by scripts/gen-go-rand.py from Go's src/math/rand/rng.go. Do not edit.\n\n"
    "extension GoRand {\n    static let cooked: [Int64] = [\n        "
    + ",\n        ".join(rows) + ",\n    ]\n}\n")
